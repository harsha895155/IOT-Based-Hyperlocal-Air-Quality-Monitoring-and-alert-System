// AirGuard Service Worker: Instant Cache Purge & Self-Unregister
// This forces any browser running stale/broken service workers to instantly purge all caches and unregister.
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.claim())
  );
});
